// a4Grafana is the Grafana A-4 provisions, or "" when A-4 is skipped — so preflight captures an undo
// only for a step that will actually run.
func a4Grafana(p Plan, in PlanInput) string {
	for _, s := range p.Steps {
		if s.ID == "A-4" && s.SkipReason == "" {
			return grafanaURL(in)
		}
	}
	return ""
}

// grafanaURL is onboarding's shared Grafana: onboard.sh:3016 (k3d) and :3183 (compose) both default
// to localhost:3000. The managed tier's is in-cluster and credentialed (SA-D24), so it has none here.
func grafanaURL(in PlanInput) string {
	if in.Tier == "compose" || in.Tier == "k3d" {
		return "http://localhost:3000"
	}
	return ""
}

// shellID turns an A-step id into a shell function suffix. `A-5a` is a legal step id and an illegal
// identifier half.
func shellID(id string) string { return strings.ReplaceAll(id, "-", "_") }
