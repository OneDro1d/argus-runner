// scripts.go — V31-001 (VR13-UP): the bash the HOST runs. This file holds what BOTH generated scripts
// share (the literals, the helpers) and preflight.sh; apply.sh is scripts_apply.go, its step bodies
// scripts_steps.go, their compensations scripts_undo.go.
//
// ⛔ NO CREDENTIAL IS EVER RENDERED. `$STAGE` outlives the update and an operator pastes what is in it
// when something goes wrong. Every token the scripts need is read from `env.<id>` BY NAME at run time.
//
// ⛔ AND EVERY OTHER VALUE IS A LITERAL. Not `$ARGUS_KIT_DIR` — the operator's shell may define it
// as something else entirely, which is VR6-S1: a block that acts on whatever happens to be set.
//
// ⭐⭐ THE MECHANISMS ARE THE KIT'S OWN, NOT INVENTED HERE. The first version of these scripts addressed
// `argus-executor-<id>` containers, a `argus-<id>` namespace, `onboarding/lib/k3d.sh`,
// `docker-compose.obs.yml` and a `skills --install` verb — none of which exists. Every test was green,
// because the fixtures were written from the same belief. The scripts now SOURCE the new kit's
// `onboarding/lib/*.sh` and port update.sh / onboard.sh line for line, citing each, and
// kit_layout_test.go derives the names from those scripts rather than restating them.
//
// ⛔ ONE BASH RULE SHAPES EVERY STEP BODY (measured, not assumed): under `set -e` WITHOUT errtrace, a
// command failing INSIDE A FUNCTION exits the script with NO ERR trap — no rollback, no outcome, no
// report. `set -E` is not the cure: it runs the trap inside every failing `$(…)` subshell. So every
// function a step calls passes failure up with `|| return 1`, and is called as `fn || false`, which
// fails at top level where the trap is armed. And `if ! fn` masks a failure in the middle of fn, so
// the undo functions carry `|| return 1` on every effect for the same reason.

