// helperUserShell decides, in the generated shell, WHO the update's helper containers run as (AC-D60, #394).
// Only a LINUX host with a NON-ROOT operator gets `--user <uid>:<gid>`: there the standard root Docker daemon
// hands the host root-owned files. Git Bash (uname MINGW*/MSYS*), macOS and a root operator are left exactly as
// they were — a Windows uid names no container user, and Docker Desktop / Rancher Desktop hand files to the host
// user themselves. ONE line, shared by the update block (updatecmd.go) and both generated scripts, so the three
// cannot disagree; every helper `docker run` expands it as ${HELPER_USER:+--user "$HELPER_USER" -e HOME=/tmp}.
//
// ⛔ NOT ON A DAEMON THAT REMAPS UIDS (reviewer, AC-D60). Rootless Docker, a daemon with userns-remap, and Podman
// behind a `docker` shim already map the container's root to the operator — which is why the update works there
// today. `--user <uid>` inside that user namespace lands on a SUBORDINATE uid on the host, so the helpers would
// write files the operator cannot read: the same defect, moved onto the machines it does not affect now. Those
// daemons say so in `docker info` (name=rootless / name=userns) and `docker --version` ("podman").
const helperUserShell = `HELPER_USER=""; if [ "$(uname -s)" = Linux ] && [ "$(id -u)" != 0 ]; then DOCKER_REMAP="$(docker info --format '{{.SecurityOptions}}' 2>/dev/null || true) $(docker --version 2>/dev/null || true)"; case "$DOCKER_REMAP" in *rootless*|*userns*|*odman*) ;; *) HELPER_USER="$(id -u):$(id -g)" ;; esac; fi`

